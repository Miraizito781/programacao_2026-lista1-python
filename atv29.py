alt1 = 1.80
alt2 = 1.50

igualdade = (alt1 == alt2)
diferenca = (alt1 != alt2)
maiorque = (alt1 > alt2)
menorque = (alt1 < alt2)
maiorigual = (alt1 >= alt2)
menorigual = (alt1 <= alt2)

print("As alturas são iguais?", igualdade)
print("As alturas são diferentes?", diferenca)
print("A altura número 1 é maior?", maiorque)
print("A altura número 1 é menor?", menorque)
print("A altura número 1 é maior ou igual à altura número 2?", maiorigual)
print("A altura número 1 é menor ou igual à altura número 2?", menorigual)